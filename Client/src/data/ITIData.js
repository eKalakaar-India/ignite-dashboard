export const getClustersByState = (state) => {

  if (!state) return []

  const entry = itiData.find((e) => Object.keys(e)[0] === state);

  return entry ? Object.keys(entry[state]) : [] 
}

export const getITIsByCluster = (
  state,
  district
) => {
  if (!state || !district) return [];
  const entry = itiData.find((e) => Object.keys(e)[0] === state);

  return entry ? entry[state][district] || [] : [];
}


